ALTER TABLE crm_schema.banners
    ADD COLUMN IF NOT EXISTS subtitle VARCHAR(160),
    ADD COLUMN IF NOT EXISTS video_url TEXT,
    ADD COLUMN IF NOT EXISTS cta_label VARCHAR(30),
    ADD COLUMN IF NOT EXISTS cta2_label VARCHAR(30),
    ADD COLUMN IF NOT EXISTS cta2_url VARCHAR(255);

CREATE TABLE IF NOT EXISTS crm_schema.services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    slug VARCHAR(255) NOT NULL UNIQUE,
    summary VARCHAR(160) NOT NULL,
    description TEXT NULL,
    image_url VARCHAR(255) NULL,
    service_area VARCHAR(100) NULL,
    sort_order INT NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS crm_schema.service_categories (
    service_id BIGINT NOT NULL REFERENCES crm_schema.services(id) ON DELETE CASCADE,
    category_id BIGINT NOT NULL REFERENCES crm_schema.categories(id) ON DELETE CASCADE,
    PRIMARY KEY (service_id, category_id)
);

CREATE INDEX IF NOT EXISTS idx_services_active_order
    ON crm_schema.services (is_active,sort_order,id);
CREATE INDEX IF NOT EXISTS idx_service_categories_category
    ON crm_schema.service_categories (category_id,service_id);

DROP TRIGGER IF EXISTS trg_services_updated_at ON crm_schema.services;
CREATE TRIGGER trg_services_updated_at
    BEFORE UPDATE ON crm_schema.services
    FOR EACH ROW EXECUTE FUNCTION crm_schema.set_updated_at();