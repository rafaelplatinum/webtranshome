-- Password reset OTP, phone verification, and session revocation.
-- Existing phone values are normalized only when they match an Indonesian mobile format.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM crm_schema.users
        WHERE phone_number IS NOT NULL
          AND btrim(phone_number) <> ''
          AND regexp_replace(phone_number, '[^0-9]', '', 'g') !~ '^(08[0-9]{8,11}|628[0-9]{7,11})$'
    ) THEN
        RAISE EXCEPTION 'Migration 000007: resolve invalid users.phone_number values before normalizing';
    END IF;

    IF EXISTS (
        SELECT normalized.phone
        FROM (
            SELECT CASE
                WHEN digits LIKE '08%' THEN '62' || substring(digits FROM 2)
                ELSE digits
            END AS phone
            FROM (
                SELECT regexp_replace(phone_number, '[^0-9]', '', 'g') AS digits
                FROM crm_schema.users
                WHERE phone_number IS NOT NULL AND btrim(phone_number) <> ''
            ) raw_numbers
        ) normalized
        GROUP BY normalized.phone
        HAVING count(*) > 1
    ) THEN
        RAISE EXCEPTION 'Migration 000007: resolve duplicate phone numbers after normalization';
    END IF;
END $$;

UPDATE crm_schema.users
SET phone_number = CASE
    WHEN btrim(phone_number) = '' THEN NULL
    WHEN regexp_replace(phone_number, '[^0-9]', '', 'g') LIKE '08%'
        THEN '62' || substring(regexp_replace(phone_number, '[^0-9]', '', 'g') FROM 2)
    ELSE regexp_replace(phone_number, '[^0-9]', '', 'g')
END
WHERE phone_number IS NOT NULL;

ALTER TABLE crm_schema.users ALTER COLUMN phone_number DROP NOT NULL;
ALTER TABLE crm_schema.users DROP CONSTRAINT IF EXISTS users_phone_number_key;
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_phone_number_present
    ON crm_schema.users (phone_number) WHERE phone_number IS NOT NULL;
ALTER TABLE crm_schema.users ADD COLUMN IF NOT EXISTS auth_version INTEGER NOT NULL DEFAULT 0;

CREATE TABLE crm_schema.otp_challenge (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NULL REFERENCES crm_schema.users(id) ON DELETE CASCADE,
    purpose VARCHAR(30) NOT NULL CHECK (purpose IN ('password_reset', 'phone_verify')),
    channel VARCHAR(20) NOT NULL CHECK (channel IN ('whatsapp', 'email')),
    destination_hash CHAR(64) NOT NULL,
    code_hash CHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    attempts SMALLINT NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    max_attempts SMALLINT NOT NULL DEFAULT 5 CHECK (max_attempts BETWEEN 1 AND 5),
    consumed_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_ip VARCHAR(45) NOT NULL
);
CREATE INDEX idx_otp_challenge_destination_created
    ON crm_schema.otp_challenge (destination_hash, purpose, channel, created_at DESC);
CREATE INDEX idx_otp_challenge_ip_created
    ON crm_schema.otp_challenge (request_ip, created_at DESC);
CREATE INDEX idx_otp_challenge_user_created
    ON crm_schema.otp_challenge (user_id, purpose, created_at DESC);

CREATE TABLE crm_schema.password_reset_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES crm_schema.users(id) ON DELETE CASCADE,
    channel VARCHAR(20) NOT NULL CHECK (channel IN ('whatsapp', 'email')),
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_password_reset_token_user_created
    ON crm_schema.password_reset_token (user_id, created_at DESC);

CREATE TABLE crm_schema.auth_security_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NULL REFERENCES crm_schema.users(id) ON DELETE SET NULL,
    event_type VARCHAR(80) NOT NULL,
    channel VARCHAR(20) NULL CHECK (channel IS NULL OR channel IN ('whatsapp', 'email')),
    destination_hash CHAR(64) NULL,
    request_ip VARCHAR(45) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_auth_security_events_ip_created
    ON crm_schema.auth_security_events (request_ip, created_at DESC);
CREATE INDEX idx_auth_security_events_user_created
    ON crm_schema.auth_security_events (user_id, created_at DESC);
