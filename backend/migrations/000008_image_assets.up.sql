CREATE TABLE IF NOT EXISTS crm_schema.image_assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_key VARCHAR(100) NOT NULL,
    owner_type VARCHAR(40) NULL,
    owner_id BIGINT NULL,
    file_path VARCHAR(500) NOT NULL,
    alt_text VARCHAR(255) NOT NULL,
    sort_order INT NOT NULL DEFAULT 1 CHECK (sort_order > 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    mime VARCHAR(40) NOT NULL CHECK (mime IN ('image/jpeg','image/png','image/webp')),
    size BIGINT NOT NULL CHECK (size > 0 AND size <= 2097152),
    width INT NOT NULL CHECK (width >= 64),
    height INT NOT NULL CHECK (height >= 64),
    is_dummy BOOLEAN NOT NULL DEFAULT FALSE,
    created_by BIGINT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_image_assets_admin FOREIGN KEY (created_by) REFERENCES crm_schema.users(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_image_assets_slot_order
    ON crm_schema.image_assets (slot_key, sort_order, id);
CREATE INDEX IF NOT EXISTS idx_image_assets_owner
    ON crm_schema.image_assets (owner_type, owner_id);

DROP TRIGGER IF EXISTS trg_image_assets_updated_at ON crm_schema.image_assets;
CREATE TRIGGER trg_image_assets_updated_at
    BEFORE UPDATE ON crm_schema.image_assets
    FOR EACH ROW EXECUTE FUNCTION crm_schema.set_updated_at();

